-- P5: atomic retraction/supersession propagation.
--
-- Single transaction (one plpgsql function -- atomic by Postgres function
-- semantics, no client-side multi-step orchestration) that: (1) marks the
-- source document retracted or superseded; (2) transitions its affected
-- active claims, and any cluster left with zero remaining active member
-- claims, out of active eligibility; (3) when the document was a
-- study-family primary (P4's duplicate_of_document_id target), auto-promotes
-- the fullest remaining non-retracted family member to primary using the
-- same fullness ranking src/lib/researchStudyFamily.ts already uses for
-- import-time matching (owner decision, 2026-08-02: auto-promote, not
-- manual-review-flag, not leave-orphaned); (4) the existing research_graph_*
-- views are live over these same tables, so eligibility disappears from the
-- projection immediately with no separate refresh step; (5) appends an
-- append-only audit/tombstone event naming the actor, reason, and every
-- affected identifier; (6) never deletes the original document, claim, or
-- cluster rows -- only status transitions and an audit trail, per this
-- project's provenance invariants.
--
-- "Corrected" and "superseded" share one mechanism here (p_action =
-- 'supersede', pointing research_documents.superseded_by at the replacement
-- document): the schema has never had a third state distinct from
-- retracted/superseded_by, and a correction is, mechanically, a document
-- being superseded by its corrected version. The reason text on the audit
-- event is what distinguishes "corrected" from "superseded by unrelated
-- follow-up work" -- there is no separate enum value to keep in sync.
--
-- A claim always belongs to exactly one document (research_claims.document_id),
-- so "affected claims" is exactly that document's active claims. A cluster is
-- only transitioned when NONE of its member claims remain active after this
-- change -- a cluster still independently supported by another document's
-- active claim must not be invalidated by an unrelated retraction.

-- Retire the two pre-P5 retraction mechanisms this function now subsumes and
-- makes safe to combine with supersession:
--
--   1. research_document_sync_claim_metadata (AFTER UPDATE OF ... retracted
--      ON research_documents, added by 20260728200000_research_claims_and_
--      grading.sql): fires synchronously the instant this function's own
--      document-retraction UPDATE runs, transitioning claims to 'superseded'
--      BEFORE this function's own explicit claim-transition step gets to
--      read "which claims were active." Left in place, it would silently
--      empty out affected_claim_ids on the audit event (the trigger already
--      did the work first) and it has no equivalent for the superseded_by
--      path at all, so retraction and supersession would behave
--      inconsistently. This function is now the single place that decides
--      and records which claims were affected.
--   2. mark_research_document_retracted (same migration): the retraction-
--      watch route now calls this function instead, which does everything
--      that one did (mark retracted) plus claim/cluster/study-family
--      propagation and an audit trail it never had.
--
-- Neither retirement touches research_claim_validate_and_sync (the
-- BEFORE INSERT/UPDATE literal-quote and retracted-active guard on
-- research_claims itself) -- that invariant is unrelated and stays.

drop trigger if exists research_document_sync_claim_metadata on public.research_documents;
drop function if exists public.sync_research_claims_after_document_change();
drop function if exists public.mark_research_document_retracted(uuid, timestamptz, text);

create table public.research_evidence_lifecycle_events (
  id bigint generated by default as identity primary key,
  document_id uuid not null references public.research_documents(id) on delete restrict,
  event_type text not null
    check (event_type in ('retracted', 'superseded')),
  reason text not null check (length(btrim(reason)) > 0),
  actor_type text not null default 'owner'
    check (actor_type in ('system', 'owner', 'worker')),
  actor_id uuid references auth.users(id) on delete set null,
  replacement_document_id uuid references public.research_documents(id) on delete set null,
  affected_claim_ids uuid[] not null default '{}'::uuid[],
  affected_cluster_ids uuid[] not null default '{}'::uuid[],
  promoted_primary_document_id uuid references public.research_documents(id) on delete set null,
  orphaned_duplicate_document_ids uuid[] not null default '{}'::uuid[],
  occurred_at timestamptz not null default now(),
  constraint research_evidence_lifecycle_events_owner_actor_check
    check (actor_type <> 'owner' or actor_id is not null),
  constraint research_evidence_lifecycle_events_replacement_check
    check (
      (event_type = 'superseded' and replacement_document_id is not null)
      or (event_type = 'retracted' and replacement_document_id is null)
    )
);

comment on table public.research_evidence_lifecycle_events
is 'Append-only tombstone/audit trail for P5 retraction and supersession propagation. Never updated or deleted -- see the append-only grants below. This is the audit-event mechanism for document lifecycle transitions; research_mission_events remains scoped to mission/stage/worker lifecycle and is not reused here.';
comment on column public.research_evidence_lifecycle_events.affected_claim_ids
is 'Claims that were status=active on this document immediately before this event and were transitioned to superseded by it.';
comment on column public.research_evidence_lifecycle_events.affected_cluster_ids
is 'Clusters transitioned to superseded because none of their member claims remained active after this event -- not every cluster touched, only those left with zero live support.';
comment on column public.research_evidence_lifecycle_events.promoted_primary_document_id
is 'When this document was a study-family primary (P4 duplicate_of_document_id target) with at least one non-retracted duplicate, the duplicate auto-promoted to primary using the same fullness ranking P4 uses at import time. Null when there was nothing to promote.';
comment on column public.research_evidence_lifecycle_events.orphaned_duplicate_document_ids
is 'Study-family duplicates of this document that could not be promoted because every one of them was also retracted. Surfaced for visibility, not auto-resolved.';

create index research_evidence_lifecycle_events_document_idx
  on public.research_evidence_lifecycle_events (document_id, occurred_at);

