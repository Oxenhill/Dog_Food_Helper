create or replace function public.propagate_research_document_status_change(
  p_document_id uuid,
  p_action text,
  p_replacement_document_id uuid,
  p_actor_id uuid,
  p_actor_type text,
  p_reason text
)
returns public.research_evidence_lifecycle_events
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_document public.research_documents;
  v_replacement public.research_documents;
  v_event_type text;
  v_affected_claim_ids uuid[];
  v_affected_cluster_ids uuid[];
  v_promoted_primary_document_id uuid;
  v_orphaned_duplicate_ids uuid[];
  v_event public.research_evidence_lifecycle_events;
begin
  if p_action not in ('retract', 'supersede') then
    raise exception 'Unsupported action: %', p_action;
  end if;
  if p_reason is null or length(btrim(p_reason)) = 0 then
    raise exception 'A reason is required to retract or supersede a research document';
  end if;
  if p_actor_type not in ('system', 'owner', 'worker') then
    raise exception 'Unsupported actor_type: %', p_actor_type;
  end if;
  if p_actor_type = 'owner' and p_actor_id is null then
    raise exception 'An owner actor requires an actor_id';
  end if;

  select * into v_document
  from public.research_documents
  where id = p_document_id
  for update;

  if not found then
    raise exception 'Research document % does not exist', p_document_id;
  end if;
  if v_document.retracted then
    raise exception 'Research document % is already retracted', p_document_id;
  end if;
  if v_document.superseded_by is not null then
    raise exception 'Research document % is already superseded', p_document_id;
  end if;

  if p_action = 'supersede' then
    if p_replacement_document_id is null then
      raise exception 'A replacement document is required to supersede a research document';
    end if;
    if p_replacement_document_id = p_document_id then
      raise exception 'A research document cannot supersede itself';
    end if;

    select * into v_replacement
    from public.research_documents
    where id = p_replacement_document_id
    for update;

    if not found then
      raise exception 'Replacement research document % does not exist', p_replacement_document_id;
    end if;
    if v_replacement.retracted or v_replacement.superseded_by is not null then
      raise exception 'Replacement research document % is not itself eligible (retracted or superseded)', p_replacement_document_id;
    end if;

    v_event_type := 'superseded';
  else
    if p_replacement_document_id is not null then
      raise exception 'A retraction may not specify a replacement document';
    end if;
    v_event_type := 'retracted';
  end if;

  -- Step 1: mark the source document.
  if p_action = 'retract' then
    update public.research_documents
    set retracted = true, retraction_checked_at = now()
    where id = p_document_id;
  else
    update public.research_documents
    set superseded_by = p_replacement_document_id
    where id = p_document_id;
  end if;

  -- Step 2: transition this document's currently-active claims out of eligibility.
  select coalesce(array_agg(id), '{}'::uuid[]) into v_affected_claim_ids
  from public.research_claims
  where document_id = p_document_id and status = 'active';

  update public.research_claims
  set status = 'superseded'
  where document_id = p_document_id and status = 'active';

  -- Step 3: transition any active cluster left with zero remaining active
  -- member claims. A cluster still independently supported by another
  -- document's active claim is untouched.
  select coalesce(array_agg(c.id), '{}'::uuid[]) into v_affected_cluster_ids
  from public.research_evidence_clusters c
  where c.status = 'active'
    and exists (
      select 1
      from public.research_evidence_cluster_members m
      where m.cluster_id = c.id and m.claim_id = any(v_affected_claim_ids)
    )
    and not exists (
      select 1
      from public.research_evidence_cluster_members m
      join public.research_claims rc on rc.id = m.claim_id
      where m.cluster_id = c.id and rc.status = 'active'
    );

  update public.research_evidence_clusters
  set status = 'superseded'
  where id = any(v_affected_cluster_ids);

  -- Step 4: study-family corroboration propagation. Only relevant when this
  -- document was a primary (P4 duplicate_of_document_id target) with at
  -- least one duplicate pointing at it. Candidates for promotion are never
  -- claims-bearing (P4's processing route excludes duplicate-flagged
  -- documents from the claim-drafting queue), so re-pointing them here never
  -- touches the "immutable once claims exist" invariant.
  v_promoted_primary_document_id := null;
  v_orphaned_duplicate_ids := '{}'::uuid[];

  if exists (
    select 1 from public.research_documents where duplicate_of_document_id = p_document_id
  ) then
    select id into v_promoted_primary_document_id
    from public.research_documents
    where duplicate_of_document_id = p_document_id
      and retracted = false
    order by
      (
        case when not coalesce(abstract_only, false) then 2 else 0 end
        + case when not coalesce(is_preprint, false) then 2 else 0 end
        + coalesce(
            case evidence_grade
              when 'A' then 4
              when 'B' then 3
              when 'C' then 2
              when 'D' then 1
              when 'E' then 0
            end,
            0
          )
      ) desc,
      duplicate_detected_at asc nulls last,
      id asc
    limit 1;

    if v_promoted_primary_document_id is not null then
      -- Promote first (clears its own duplicate_of_document_id so it
      -- qualifies as a primary target for the next statement, per
      -- enforce_research_document_duplicate_target's no-chains rule).
      update public.research_documents
      set duplicate_of_document_id = null
      where id = v_promoted_primary_document_id;

      update public.research_documents
      set duplicate_of_document_id = v_promoted_primary_document_id
      where duplicate_of_document_id = p_document_id
        and id <> v_promoted_primary_document_id;
    else
      select coalesce(array_agg(id), '{}'::uuid[]) into v_orphaned_duplicate_ids
      from public.research_documents
      where duplicate_of_document_id = p_document_id;
    end if;
  end if;

  -- Step 5: append-only tombstone/audit event. Never updated or deleted.
  insert into public.research_evidence_lifecycle_events (
    document_id, event_type, reason, actor_type, actor_id,
    replacement_document_id, affected_claim_ids, affected_cluster_ids,
    promoted_primary_document_id, orphaned_duplicate_document_ids
  ) values (
    p_document_id, v_event_type, p_reason, p_actor_type, p_actor_id,
    p_replacement_document_id, v_affected_claim_ids, v_affected_cluster_ids,
    v_promoted_primary_document_id, v_orphaned_duplicate_ids
  )
  returning * into v_event;

  return v_event;
end;
$function$;

comment on function public.propagate_research_document_status_change(uuid, text, uuid, uuid, text, text)
is 'P5 atomic retraction/supersession propagation. Single plpgsql function so a failure at any step rolls back every step (document status, claim/cluster transitions, study-family promotion, audit event) by ordinary Postgres transaction semantics. Callable only by the service role used by server-side admin/retraction-watch routes.';

