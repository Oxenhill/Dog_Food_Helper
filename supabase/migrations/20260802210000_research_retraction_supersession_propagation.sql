-- Graph projection: SUPERSEDES and RETRACTED_BY, deferred to P5 explicitly by
-- 20260802170000_research_graph_projection.sql's own comment ("A retracted/
-- superseded document has no node in this projection at all ... belongs to
-- whichever phase defines it"). Both are tombstone edges by necessity: the
-- old/retracted side is never itself an eligible research_graph_documents
-- node (that is the point of retraction), so unlike P4's SAME_STUDY_FAMILY
-- edge (which requires both endpoints to be eligible nodes), only the
-- "still-live" side of each of these edges is required to resolve to a node.
--
-- SUPERSEDES connects the new/replacement document (must be an eligible
-- node) back to the old, tombstoned document (by raw id, never a node).
-- RETRACTED_BY has no replacement document to point to for a pure retraction,
-- so it terminates at the audit event instead (reason/actor/timestamp) rather
-- than at another document. This edge-shape choice is a graph-presentation
-- decision, not a product-policy one; flagged here for owner review like any
-- other durable technical choice, not gated on it.

create or replace view public.research_graph_edges_supersedes
with (security_invoker = true) as
select
  'SUPERSEDES'::text as edge_type,
  d.document_id as new_document_id,
  rd.id as old_document_id,
  rd.title as old_document_title,
  e.reason,
  e.occurred_at
from public.research_documents rd
join public.research_graph_documents d on d.document_id = rd.superseded_by
left join public.research_evidence_lifecycle_events e
  on e.document_id = rd.id and e.event_type = 'superseded'
where rd.superseded_by is not null;

comment on view public.research_graph_edges_supersedes
is 'P5 graph edge: new document SUPERSEDES old (tombstoned) document. Only the new/replacement side must be an eligible research_graph_documents node.';

create or replace view public.research_graph_edges_retracted_by
with (security_invoker = true) as
select
  'RETRACTED_BY'::text as edge_type,
  rd.id as document_id,
  rd.title as document_title,
  e.id as lifecycle_event_id,
  e.reason,
  e.actor_type,
  e.occurred_at
from public.research_documents rd
join public.research_evidence_lifecycle_events e
  on e.document_id = rd.id and e.event_type = 'retracted'
where rd.retracted = true
  and rd.superseded_by is null;

comment on view public.research_graph_edges_retracted_by
is 'P5 graph edge: retracted document RETRACTED_BY its lifecycle/audit event. A pure retraction has no replacement document, so the tombstone edge terminates at the audit event (reason/actor/timestamp) rather than at another document.';

revoke all on public.research_graph_edges_supersedes from public, anon, authenticated;
revoke all on public.research_graph_edges_retracted_by from public, anon, authenticated;
grant select on public.research_graph_edges_supersedes to service_role;
grant select on public.research_graph_edges_retracted_by to service_role;
