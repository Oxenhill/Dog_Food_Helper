create or replace function public.validate_research_mission_stage_retry()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  previous_stage public.research_mission_stages%rowtype;
begin
  if new.retry_of_stage_id is null then
    return new;
  end if;

  select *
  into previous_stage
  from public.research_mission_stages
  where id = new.retry_of_stage_id;

  if previous_stage.id is null
    or previous_stage.mission_id <> new.mission_id
    or previous_stage.stage_key <> new.stage_key
    or previous_stage.attempt_number >= new.attempt_number then
    raise exception 'Retry stage must reference an earlier attempt of the same mission stage';
  end if;

  return new;
end;
$$;

create trigger research_mission_stage_retry_validate
before insert or update of mission_id, stage_key, attempt_number, retry_of_stage_id
on public.research_mission_stages
for each row execute function public.validate_research_mission_stage_retry();

create or replace function public.validate_research_ingestion_job_mission_links()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  linked_mission_id uuid;
begin
  if tg_op = 'UPDATE'
    and old.mission_id is not null
    and (
      new.mission_id is distinct from old.mission_id
      or new.mission_stage_id is distinct from old.mission_stage_id
    ) then
    raise exception 'Research ingestion job mission links are immutable once assigned';
  end if;

  if new.mission_id is null and new.mission_stage_id is null then
    return new;
  end if;
  if new.mission_id is null or new.mission_stage_id is null then
    raise exception 'Mission and mission stage links must both be set or both be null';
  end if;

  select mission_id
  into linked_mission_id
  from public.research_mission_stages
  where id = new.mission_stage_id;

  if linked_mission_id is null or linked_mission_id <> new.mission_id then
    raise exception 'Research ingestion job stage does not belong to its mission';
  end if;
  return new;
end;
$$;

create trigger research_ingestion_job_mission_links_validate
before insert or update of mission_id, mission_stage_id
on public.research_ingestion_jobs
for each row execute function public.validate_research_ingestion_job_mission_links();

