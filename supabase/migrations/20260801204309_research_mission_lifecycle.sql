create or replace function public.append_research_mission_event(
  p_mission_id uuid,
  p_mission_stage_id uuid,
  p_event_type text,
  p_actor_type text default 'worker',
  p_actor_id uuid default null,
  p_payload jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  next_sequence bigint;
  inserted_id bigint;
  linked_mission_id uuid;
begin
  if not exists (select 1 from public.research_missions where id = p_mission_id) then
    raise exception 'Research mission not found';
  end if;

  if p_mission_stage_id is not null then
    select mission_id
    into linked_mission_id
    from public.research_mission_stages
    where id = p_mission_stage_id;
    if linked_mission_id is null or linked_mission_id <> p_mission_id then
      raise exception 'Research mission event stage does not belong to mission';
    end if;
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_mission_id::text, 0));
  select coalesce(max(sequence_number), 0) + 1
  into next_sequence
  from public.research_mission_events
  where mission_id = p_mission_id;

  insert into public.research_mission_events (
    mission_id,
    mission_stage_id,
    sequence_number,
    event_type,
    actor_type,
    actor_id,
    payload
  ) values (
    p_mission_id,
    p_mission_stage_id,
    next_sequence,
    p_event_type,
    p_actor_type,
    p_actor_id,
    coalesce(p_payload, '{}'::jsonb)
  )
  returning id into inserted_id;

  return inserted_id;
end;
$$;

create or replace function public.start_research_mission_job(
  p_mission_type text,
  p_objective text,
  p_stage_key text,
  p_job_type text,
  p_requested_by uuid,
  p_input jsonb default '{}'::jsonb,
  p_initial_status text default 'running',
  p_gateway_model text default null,
  p_idempotency_key text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  new_mission public.research_missions%rowtype;
  new_stage public.research_mission_stages%rowtype;
  new_job public.research_ingestion_jobs%rowtype;
  existing_job public.research_ingestion_jobs%rowtype;
  started_time timestamptz;
begin
  if p_initial_status not in ('queued', 'running') then
    raise exception 'Initial research mission job status must be queued or running';
  end if;
  if jsonb_typeof(coalesce(p_input, '{}'::jsonb)) <> 'object' then
    raise exception 'Research mission input must be a JSON object';
  end if;

  if p_idempotency_key is not null then
    perform pg_advisory_xact_lock(hashtextextended(p_idempotency_key, 1));
    select job.*
    into existing_job
    from public.research_mission_stages stage
    join public.research_ingestion_jobs job on job.mission_stage_id = stage.id
    where stage.idempotency_key = p_idempotency_key;
    if existing_job.id is not null then
      if existing_job.requested_by <> p_requested_by
        or existing_job.job_type <> p_job_type
        or existing_job.input <> coalesce(p_input, '{}'::jsonb)
        or not exists (
          select 1
          from public.research_mission_stages stage
          join public.research_missions mission on mission.id = stage.mission_id
          where stage.id = existing_job.mission_stage_id
            and stage.stage_key = p_stage_key
            and mission.mission_type = p_mission_type
        ) then
        raise exception 'Research mission idempotency key was reused for different input';
      end if;
      return to_jsonb(existing_job);
    end if;
  end if;

  started_time := case when p_initial_status = 'running' then now() else null end;

  insert into public.research_missions (
    mission_type,
    objective,
    status,
    requested_by,
    input,
    current_stage_key,
    started_at
  ) values (
    p_mission_type,
    p_objective,
    p_initial_status,
    p_requested_by,
    coalesce(p_input, '{}'::jsonb),
    p_stage_key,
    started_time
  )
  returning * into new_mission;

  insert into public.research_mission_stages (
    mission_id,
    stage_key,
    status,
    idempotency_key,
    input,
    started_at
  ) values (
    new_mission.id,
    p_stage_key,
    case when p_initial_status = 'running' then 'running' else 'pending' end,
    p_idempotency_key,
    coalesce(p_input, '{}'::jsonb),
    started_time
  )
  returning * into new_stage;

  insert into public.research_ingestion_jobs (
    job_type,
    status,
    requested_by,
    input,
    gateway_model,
    started_at,
    mission_id,
    mission_stage_id
  ) values (
    p_job_type,
    p_initial_status,
    p_requested_by,
    coalesce(p_input, '{}'::jsonb),
    p_gateway_model,
    started_time,
    new_mission.id,
    new_stage.id
  )
  returning * into new_job;

  perform public.append_research_mission_event(
    new_mission.id,
    null,
    'mission.created',
    'owner',
    p_requested_by,
    jsonb_build_object(
      'mission_type', p_mission_type,
      'status', p_initial_status,
      'job_id', new_job.id
    )
  );
  perform public.append_research_mission_event(
    new_mission.id,
    new_stage.id,
    case when p_initial_status = 'running' then 'stage.started' else 'stage.queued' end,
    'owner',
    p_requested_by,
    jsonb_build_object(
      'stage_key', p_stage_key,
      'attempt_number', 1,
      'job_id', new_job.id
    )
  );

  return to_jsonb(new_job);
end;
$$;

create or replace function public.mark_research_mission_job_running(
  p_job_id uuid,
  p_payload jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  linked_job public.research_ingestion_jobs%rowtype;
  linked_mission public.research_missions%rowtype;
  started_time timestamptz := now();
begin
  select * into linked_job
  from public.research_ingestion_jobs
  where id = p_job_id
  for update;

  if linked_job.id is null or linked_job.mission_id is null or linked_job.mission_stage_id is null then
    raise exception 'Linked research mission job not found';
  end if;
  if linked_job.status = 'running' then
    return to_jsonb(linked_job);
  end if;
  if linked_job.status <> 'queued' then
    raise exception 'Only queued research mission jobs can start running';
  end if;

  select * into linked_mission
  from public.research_missions
  where id = linked_job.mission_id
  for update;

  update public.research_ingestion_jobs
  set status = 'running', started_at = started_time, updated_at = started_time
  where id = p_job_id
  returning * into linked_job;

  update public.research_mission_stages
  set status = 'running', started_at = started_time
  where id = linked_job.mission_stage_id;

  update public.research_missions
  set status = 'running', started_at = coalesce(started_at, started_time)
  where id = linked_job.mission_id;

  if linked_mission.status = 'queued' then
    perform public.append_research_mission_event(
      linked_job.mission_id,
      null,
      'mission.started',
      'worker',
      null,
      jsonb_build_object('job_id', linked_job.id)
    );
  end if;
  perform public.append_research_mission_event(
    linked_job.mission_id,
    linked_job.mission_stage_id,
    'stage.started',
    'worker',
    null,
    jsonb_build_object('job_id', linked_job.id) || coalesce(p_payload, '{}'::jsonb)
  );

  return to_jsonb(linked_job);
end;
$$;

create or replace function public.retry_research_mission_job_stage(
  p_failed_job_id uuid,
  p_requested_by uuid,
  p_idempotency_key text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  failed_job public.research_ingestion_jobs%rowtype;
  failed_stage public.research_mission_stages%rowtype;
  linked_mission public.research_missions%rowtype;
  retry_stage public.research_mission_stages%rowtype;
  retry_job public.research_ingestion_jobs%rowtype;
  existing_job public.research_ingestion_jobs%rowtype;
  next_attempt smallint;
begin
  if p_idempotency_key is not null then
    perform pg_advisory_xact_lock(hashtextextended(p_idempotency_key, 2));
  end if;

  select * into failed_job
  from public.research_ingestion_jobs
  where id = p_failed_job_id
  for update;
  if failed_job.id is null
    or failed_job.status <> 'failed'
    or failed_job.mission_id is null
    or failed_job.mission_stage_id is null then
    raise exception 'Only a failed linked research mission job can be retried';
  end if;

  select * into failed_stage
  from public.research_mission_stages
  where id = failed_job.mission_stage_id
  for update;
  if failed_stage.id is null or failed_stage.status <> 'failed' then
    raise exception 'Failed research mission stage not found';
  end if;

  select * into linked_mission
  from public.research_missions
  where id = failed_job.mission_id
  for update;
  if linked_mission.id is null or linked_mission.requested_by <> p_requested_by then
    raise exception 'Research mission retry requester does not match mission owner';
  end if;

  if p_idempotency_key is not null then
    select job.*
    into existing_job
    from public.research_mission_stages stage
    join public.research_ingestion_jobs job on job.mission_stage_id = stage.id
    where stage.idempotency_key = p_idempotency_key;
    if existing_job.id is not null then
      if existing_job.requested_by <> p_requested_by
        or not exists (
          select 1
          from public.research_mission_stages stage
          where stage.id = existing_job.mission_stage_id
            and stage.retry_of_stage_id = failed_stage.id
        ) then
        raise exception 'Research retry idempotency key was reused for a different attempt';
      end if;
      return to_jsonb(existing_job);
    end if;
  end if;

  select job.*
  into existing_job
  from public.research_mission_stages stage
  join public.research_ingestion_jobs job on job.mission_stage_id = stage.id
  where stage.retry_of_stage_id = failed_stage.id
  order by stage.attempt_number desc
  limit 1;
  if existing_job.id is not null then
    return to_jsonb(existing_job);
  end if;

  select (coalesce(max(attempt_number), 0) + 1)::smallint
  into next_attempt
  from public.research_mission_stages
  where mission_id = failed_stage.mission_id
    and stage_key = failed_stage.stage_key;

  insert into public.research_mission_stages (
    mission_id,
    stage_key,
    attempt_number,
    retry_of_stage_id,
    status,
    idempotency_key,
    input
  ) values (
    failed_stage.mission_id,
    failed_stage.stage_key,
    next_attempt,
    failed_stage.id,
    'pending',
    p_idempotency_key,
    failed_job.input
  )
  returning * into retry_stage;

  insert into public.research_ingestion_jobs (
    job_type,
    status,
    requested_by,
    input,
    gateway_model,
    mission_id,
    mission_stage_id
  ) values (
    failed_job.job_type,
    'queued',
    p_requested_by,
    failed_job.input,
    failed_job.gateway_model,
    failed_job.mission_id,
    retry_stage.id
  )
  returning * into retry_job;

  update public.research_missions
  set
    status = 'queued',
    current_stage_key = failed_stage.stage_key,
    result_summary = '{}'::jsonb,
    terminal_reason_code = null,
    terminal_message = null,
    completed_at = null
  where id = failed_job.mission_id;

  perform public.append_research_mission_event(
    failed_job.mission_id,
    retry_stage.id,
    'stage.retry_queued',
    'owner',
    p_requested_by,
    jsonb_build_object(
      'job_id', retry_job.id,
      'retry_of_job_id', failed_job.id,
      'retry_of_stage_id', failed_stage.id,
      'attempt_number', next_attempt
    )
  );
  perform public.append_research_mission_event(
    failed_job.mission_id,
    null,
    'mission.retry_queued',
    'owner',
    p_requested_by,
    jsonb_build_object(
      'job_id', retry_job.id,
      'retry_of_job_id', failed_job.id,
      'stage_key', failed_stage.stage_key,
      'attempt_number', next_attempt
    )
  );

  return to_jsonb(retry_job);
end;
$$;

create or replace function public.finish_research_mission_job(
  p_job_id uuid,
  p_job_status text,
  p_result_summary jsonb default null,
  p_reason_code text default null,
  p_error_message text default null,
  p_gateway_model text default null,
  p_gateway_input_tokens bigint default null,
  p_gateway_output_tokens bigint default null,
  p_gateway_cost_usd numeric default null,
  p_event_payload jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  linked_job public.research_ingestion_jobs%rowtype;
  finished_time timestamptz := now();
  stage_status text;
  mission_status text;
  stage_event_type text;
  mission_event_type text;
begin
  if p_job_status not in ('awaiting_selection', 'succeeded', 'failed') then
    raise exception 'Unsupported terminal research ingestion job status';
  end if;
  if p_job_status = 'failed' and length(btrim(coalesce(p_reason_code, ''))) = 0 then
    raise exception 'A deterministic reason code is required for failed research mission jobs';
  end if;
  if p_job_status = 'failed' and length(btrim(coalesce(p_error_message, ''))) = 0 then
    raise exception 'An error message is required for failed research mission jobs';
  end if;
  if p_result_summary is not null and jsonb_typeof(p_result_summary) <> 'object' then
    raise exception 'Research mission result summary must be a JSON object';
  end if;

  select * into linked_job
  from public.research_ingestion_jobs
  where id = p_job_id
  for update;

  if linked_job.id is null or linked_job.mission_id is null or linked_job.mission_stage_id is null then
    raise exception 'Linked research mission job not found';
  end if;
  if linked_job.status = p_job_status then
    return to_jsonb(linked_job);
  end if;
  if linked_job.status not in ('queued', 'running') then
    raise exception 'Research mission job is already terminal';
  end if;

  stage_status := case when p_job_status = 'failed' then 'failed' else 'succeeded' end;
  mission_status := case when p_job_status = 'failed' then 'failed' else 'completed' end;
  stage_event_type := case when p_job_status = 'failed' then 'stage.failed' else 'stage.succeeded' end;
  mission_event_type := case when p_job_status = 'failed' then 'mission.failed' else 'mission.completed' end;

  update public.research_ingestion_jobs
  set
    status = p_job_status,
    result_summary = coalesce(p_result_summary, result_summary),
    error_message = case when p_job_status = 'failed' then p_error_message else null end,
    gateway_model = coalesce(p_gateway_model, gateway_model),
    gateway_input_tokens = coalesce(p_gateway_input_tokens, gateway_input_tokens),
    gateway_output_tokens = coalesce(p_gateway_output_tokens, gateway_output_tokens),
    gateway_cost_usd = coalesce(p_gateway_cost_usd, gateway_cost_usd),
    started_at = coalesce(started_at, finished_time),
    completed_at = finished_time,
    updated_at = finished_time
  where id = p_job_id
  returning * into linked_job;

  update public.research_mission_stages
  set
    status = stage_status,
    result_summary = coalesce(p_result_summary, result_summary),
    reason_code = case when p_job_status = 'failed' then p_reason_code else null end,
    error_message = case when p_job_status = 'failed' then p_error_message else null end,
    started_at = coalesce(started_at, finished_time),
    completed_at = finished_time
  where id = linked_job.mission_stage_id;

  update public.research_missions
  set
    status = mission_status,
    result_summary = coalesce(p_result_summary, result_summary),
    terminal_reason_code = case when p_job_status = 'failed' then p_reason_code else null end,
    terminal_message = case when p_job_status = 'failed' then p_error_message else null end,
    started_at = coalesce(started_at, finished_time),
    completed_at = finished_time
  where id = linked_job.mission_id;

  perform public.append_research_mission_event(
    linked_job.mission_id,
    linked_job.mission_stage_id,
    stage_event_type,
    'worker',
    null,
    jsonb_build_object(
      'job_id', linked_job.id,
      'job_status', p_job_status,
      'reason_code', p_reason_code
    ) || coalesce(p_event_payload, '{}'::jsonb)
  );
  perform public.append_research_mission_event(
    linked_job.mission_id,
    null,
    mission_event_type,
    'worker',
    null,
    jsonb_build_object(
      'job_id', linked_job.id,
      'status', mission_status,
      'reason_code', p_reason_code
    )
  );

  return to_jsonb(linked_job);
end;
$$;

create or replace function public.append_research_mission_job_event(
  p_job_id uuid,
  p_event_type text,
  p_payload jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  linked_job public.research_ingestion_jobs%rowtype;
begin
