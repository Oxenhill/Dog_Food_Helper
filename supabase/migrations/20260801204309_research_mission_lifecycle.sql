-- Research mission lifecycle and durable audit events.
--
-- This is an additive control-plane layer over research_ingestion_jobs. It does
-- not backfill or reinterpret existing jobs, documents, claims, clusters, review
-- decisions, recommendation evidence, or runtime ranking. New server-side
-- operations create a mission, one stage attempt, and the existing executable
-- job atomically through service-role-only functions.

create table public.research_missions (
  id uuid primary key default gen_random_uuid(),
  mission_type text not null
    check (mission_type in (
      'discovery',
      'source_import',
      'document_processing',
      'claim_drafting',
      'clustering',
      'review_handoff'
    )),
  objective text not null check (length(btrim(objective)) > 0),
  status text not null default 'queued'
    check (status in ('queued', 'running', 'completed', 'partial', 'failed', 'cancelled')),
  requested_by uuid not null references auth.users(id) on delete restrict,
  input jsonb not null default '{}'::jsonb
    check (jsonb_typeof(input) = 'object'),
  result_summary jsonb not null default '{}'::jsonb
    check (jsonb_typeof(result_summary) = 'object'),
  current_stage_key text,
  terminal_reason_code text,
  terminal_message text,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint research_missions_reason_code_check
    check (
      terminal_reason_code is null
      or terminal_reason_code ~ '^[a-z][a-z0-9_]*$'
    ),
  constraint research_missions_terminal_reason_check
    check (
      status not in ('partial', 'failed', 'cancelled')
      or length(btrim(coalesce(terminal_reason_code, ''))) > 0
    ),
  constraint research_missions_running_time_check
    check (status <> 'running' or started_at is not null),
  constraint research_missions_completed_time_check
    check (
      (status in ('completed', 'partial', 'failed', 'cancelled') and completed_at is not null)
      or (status in ('queued', 'running') and completed_at is null)
    )
);

create table public.research_mission_stages (
  id uuid primary key default gen_random_uuid(),
  mission_id uuid not null references public.research_missions(id) on delete restrict,
  stage_key text not null
    check (stage_key in (
      'discovery',
      'source_acquisition',
      'document_ingestion',
      'relevance_selection',
      'claim_drafting',
      'clustering',
      'review_handoff'
    )),
  attempt_number smallint not null default 1 check (attempt_number > 0),
  retry_of_stage_id uuid references public.research_mission_stages(id) on delete restrict,
  status text not null default 'pending'
    check (status in ('pending', 'running', 'succeeded', 'partial', 'failed', 'skipped', 'cancelled')),
  idempotency_key text,
  input jsonb not null default '{}'::jsonb
    check (jsonb_typeof(input) = 'object'),
  result_summary jsonb not null default '{}'::jsonb
    check (jsonb_typeof(result_summary) = 'object'),
  reason_code text,
  error_message text,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint research_mission_stages_attempt_key
    unique (mission_id, stage_key, attempt_number),
  constraint research_mission_stages_idempotency_key_check
    check (idempotency_key is null or length(btrim(idempotency_key)) > 0),
  constraint research_mission_stages_reason_code_check
    check (reason_code is null or reason_code ~ '^[a-z][a-z0-9_]*$'),
  constraint research_mission_stages_terminal_reason_check
    check (
      status not in ('partial', 'failed', 'skipped', 'cancelled')
      or length(btrim(coalesce(reason_code, ''))) > 0
    ),
  constraint research_mission_stages_retry_check
    check (
      (attempt_number = 1 and retry_of_stage_id is null)
      or (attempt_number > 1 and retry_of_stage_id is not null)
    ),
  constraint research_mission_stages_running_time_check
    check (status <> 'running' or started_at is not null),
  constraint research_mission_stages_completed_time_check
    check (
      (status in ('succeeded', 'partial', 'failed', 'skipped', 'cancelled') and completed_at is not null)
      or (status in ('pending', 'running') and completed_at is null)
    )
);

create unique index research_mission_stages_idempotency_idx
  on public.research_mission_stages (idempotency_key)
  where idempotency_key is not null;
create index research_mission_stages_mission_idx
  on public.research_mission_stages (mission_id, created_at, attempt_number);
create index research_mission_stages_retry_idx
  on public.research_mission_stages (retry_of_stage_id)
  where retry_of_stage_id is not null;

create table public.research_mission_events (
  id bigint generated by default as identity primary key,
  mission_id uuid not null references public.research_missions(id) on delete restrict,
  mission_stage_id uuid references public.research_mission_stages(id) on delete restrict,
  sequence_number bigint not null check (sequence_number > 0),
  event_type text not null
    check (event_type ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$'),
  actor_type text not null default 'worker'
    check (actor_type in ('system', 'owner', 'worker')),
  actor_id uuid references auth.users(id) on delete set null,
  payload jsonb not null default '{}'::jsonb
    check (jsonb_typeof(payload) = 'object'),
  occurred_at timestamptz not null default now(),
  constraint research_mission_events_sequence_key unique (mission_id, sequence_number),
  constraint research_mission_events_owner_actor_check
    check (actor_type <> 'owner' or actor_id is not null)
);

create index research_mission_events_mission_idx
  on public.research_mission_events (mission_id, sequence_number);
create index research_mission_events_stage_idx
  on public.research_mission_events (mission_stage_id, sequence_number)
  where mission_stage_id is not null;
create index research_missions_status_idx
  on public.research_missions (status, created_at desc);
create index research_missions_requester_idx
  on public.research_missions (requested_by, created_at desc);

alter table public.research_ingestion_jobs
  add column mission_id uuid references public.research_missions(id) on delete set null,
  add column mission_stage_id uuid references public.research_mission_stages(id) on delete set null;

create index research_ingestion_jobs_mission_idx
  on public.research_ingestion_jobs (mission_id, created_at desc)
  where mission_id is not null;
create unique index research_ingestion_jobs_mission_stage_idx
  on public.research_ingestion_jobs (mission_stage_id)
  where mission_stage_id is not null;

